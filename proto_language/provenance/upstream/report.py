"""Render the upstream lock as a human-readable audit (``registry/upstream/AUDIT.md``).

The audit answers, per toolkit: what code and weights does it pull, from where,
and which of those references can still change underneath us. It is
regenerated with the lock and reviewed in the same PR.

Examples:
    >>> from proto_language.provenance.upstream.report import render_audit
    >>> text = render_audit(lock)  # doctest: +SKIP
    >>> text.startswith("# Upstream audit")  # True
"""

from __future__ import annotations

from collections import Counter

from proto_language.provenance.upstream.sources import UpstreamLock, UpstreamSource

__all__ = ["render_audit"]

_ROLE_ORDER = ("weights", "code", "data", "binary", "dependency")


def _cell(src: UpstreamSource) -> str:
    flag = {"pinned": "pinned", "floating": "**floating**", "unresolved": "unresolved", "missing": "**missing**"}
    extra = " (template)" if src.template else ""
    return f"`{src.id}` {flag[src.status]}{extra}"


def _action(src: UpstreamSource) -> str | None:
    """One-line remediation for a source that is not pinned."""
    if src.status == "pinned":
        return None
    if src.type in ("hf-model", "hf-dataset"):
        return "pass an explicit `revision=<commit sha>` (or declare it) and mirror the files"
    if src.type == "git":
        if src.resolved.get("abbreviated_commit"):
            return "expand the abbreviated SHA to the full 40-hex commit"
        return "pin a full commit SHA (`git checkout <sha>` / `@<sha>` in the requirement)"
    if src.type == "url":
        if src.template:
            return "declare the concrete URL(s) in declarations.yaml"
        return "mirror into the CAS so the SHA-256 is recorded"
    if src.type == "pypi":
        return "pin with `==` (or rely on the hash-locked env lock)"
    return None


def render_audit(lock: UpstreamLock, max_rows_per_toolkit: int = 8) -> str:
    """Render the audit Markdown.

    Args:
        lock (UpstreamLock): Resolved lock.
        max_rows_per_toolkit (int): Cap on non-dependency rows listed per toolkit.

    Returns:
        str: Markdown document.
    """
    lines = [
        "# Upstream audit",
        "",
        "Generated by `python -m proto_language.provenance upstream resolve`. Do not edit by hand;",
        "fix discovery mistakes in `declarations.yaml`. See `notes/upstream-control.md`.",
        "",
        f"proto-tools commit: `{lock.proto_tools_commit}`",
        "",
        "## Summary",
        "",
        "| Type | pinned | floating | unresolved | missing |",
        "|---|---:|---:|---:|---:|",
    ]
    counts: Counter[tuple[str, str]] = Counter((s.type, s.status) for s in lock.sources.values())
    for kind in ("git", "pypi", "hf-model", "hf-dataset", "url"):
        row = [str(counts.get((kind, st), 0)) for st in ("pinned", "floating", "unresolved", "missing")]
        lines.append(f"| {kind} | " + " | ".join(row) + " |")
    roles = Counter((s.role, s.status == "pinned") for s in lock.sources.values())
    lines += [
        "",
        f"Weights sources: {roles[('weights', True)] + roles[('weights', False)]} "
        f"({roles[('weights', True)]} pinned). Code sources: {roles[('code', True)] + roles[('code', False)]} "
        f"({roles[('code', True)]} pinned).",
        "",
        "Status meanings: **pinned** = an immutable identifier is recorded (full commit SHA, `==` version",
        "with file hashes, HF revision SHA, or mirrored SHA-256). **floating** = reachable, but the toolkit",
        "fetches a moving reference. **unresolved** = not yet resolved (network policy, template URL).",
        "",
        "## Weights not pinned (highest priority)",
        "",
        "| Toolkit | Source | Fix |",
        "|---|---|---|",
    ]
    for name, entry in sorted(lock.toolkits.items()):
        for sid in entry.sources:
            src = lock.sources[sid]
            if src.role == "weights" and src.status != "pinned":
                lines.append(f"| {name} | {_cell(src)} | {_action(src)} |")
    lines += ["", "## Per toolkit", ""]
    for name, entry in sorted(lock.toolkits.items()):
        srcs = [lock.sources[sid] for sid in entry.sources]
        tally = Counter(s.status for s in srcs)
        lic = entry.license.get("code", {}) if isinstance(entry.license.get("code"), dict) else {}
        weights_lic = entry.license.get("weights", {}) if isinstance(entry.license.get("weights"), dict) else {}
        lines.append(f"### {name} ({entry.category})")
        lines.append("")
        lines.append(
            f"env: `{entry.env_name or '-'}` · code license: `{lic.get('spdx', '?')}` · "
            f"weights license: `{weights_lic.get('spdx', '-')}` · "
            + ", ".join(f"{k}: {v}" for k, v in sorted(tally.items()))
        )
        if entry.services:
            lines.append(f"live services (not mirrorable): {', '.join(entry.services)}")
        if entry.notes:
            lines.append(f"notes: {entry.notes}")
        lines.append("")
        shown = sorted((s for s in srcs if s.role != "dependency"), key=lambda s: (_ROLE_ORDER.index(s.role), s.id))[
            :max_rows_per_toolkit
        ]
        for src in shown:
            own = [loc for loc in src.found_in if f"/{name}/" in loc]
            where = (own or src.found_in or ["-"])[0]
            lines.append(f"- {src.role}: {_cell(src)} — `{where}`")
        deps = [s for s in srcs if s.role == "dependency"]
        if deps:
            floating = sum(1 for s in deps if s.status != "pinned")
            lines.append(f"- dependencies: {len(deps)} PyPI requirements ({floating} not `==`-pinned)")
        lines.append("")
    return "\n".join(lines) + "\n"
